-- One row per (install, day). Re-posting the same day replaces the row (the extension retries after failures).
CREATE TABLE IF NOT EXISTS daily (
  install     TEXT NOT NULL,      -- random id generated by the extension when the user opts in
  day         TEXT NOT NULL,      -- YYYY-MM-DD, the user's local calendar day
  version     TEXT NOT NULL DEFAULT '',
  lang        TEXT NOT NULL DEFAULT '',
  lookups     INTEGER NOT NULL DEFAULT 0,
  found       INTEGER NOT NULL DEFAULT 0,
  uncertain   INTEGER NOT NULL DEFAULT 0,
  not_found   INTEGER NOT NULL DEFAULT 0,
  skipped     INTEGER NOT NULL DEFAULT 0,
  cached      INTEGER NOT NULL DEFAULT 0,
  usd         REAL    NOT NULL DEFAULT 0,
  steps       TEXT    NOT NULL DEFAULT '{}',   -- JSON { step: { calls, hits, errors } }
  sources     TEXT    NOT NULL DEFAULT '{}',   -- JSON { gmail: n, outlook: n, ... }
  received_at TEXT    NOT NULL,
  PRIMARY KEY (install, day)
);
CREATE INDEX IF NOT EXISTS daily_day ON daily (day);
